@app.command(hidden=True)
def report(config: Path = typer.Option(Path("configs/evaluation.yaml"), exists=True), experiment_id: str | None = typer.Option(None), model: str | None = typer.Option(None)):
    """Regenerate per-model summaries and reports from evaluated outputs."""
    cfg = _config(config); experiment = cfg.project.output_dir / str(experiment_id or cfg.project.experiment_id)
    model_dirs = [experiment / model] if model else sorted(path for path in experiment.iterdir() if path.is_dir() and (path / "results.csv").exists())
    for directory in model_dirs:
        frame = pd.read_csv(directory / "results.csv", keep_default_na=False); metrics = calculate_metrics(frame); metrics["model_id"] = directory.name
        (directory / "model_summary.json").write_text(json.dumps(metrics, indent=2), encoding="utf-8"); generate_model_report(directory, directory.name, metrics, cfg.reporting.generate_pdf)
        typer.echo(f"Generated report for {directory.name}")


@app.command(hidden=True)
def compare(config: Path = typer.Option(Path("configs/evaluation.yaml"), exists=True), experiment_id: str | None = typer.Option(None)):
    """Regenerate the cross-model comparison."""
    cfg = _config(config); experiment = cfg.project.output_dir / str(experiment_id or cfg.project.experiment_id)
    frames = {}; summaries = {}
    for directory in sorted(path for path in experiment.iterdir() if path.is_dir() and (path / "results.csv").exists()):
        frames[directory.name] = pd.read_csv(directory / "results.csv", keep_default_na=False)
        summaries[directory.name] = json.loads((directory / "model_summary.json").read_text(encoding="utf-8"))
    output = generate_comparison(experiment, summaries, frames, cfg.reporting.generate_pdf); typer.echo(f"Comparison output: {output}")


