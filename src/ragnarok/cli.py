@models_app.command("check")
def models_check(config: Path = typer.Option(Path("configs/evaluation.yaml"), exists=True)):
    """Check configured model providers without downloading models."""
    async def check_all():
        cfg = _config(config); failed = False
        for model in cfg.models + ([cfg.judge.model] if cfg.judge.enabled and cfg.judge.model else []):
            ok, detail = await provider_for(model, cfg.runtime).check(); typer.echo(f"{model.id}: {'OK' if ok else 'UNAVAILABLE'} - {detail}"); failed |= not ok
        return failed
    if asyncio.run(check_all()):
        raise typer.Exit(1)


@app.command("run")
def run_command(
    config: Path = typer.Option(Path("configs/evaluation.yaml"), exists=True),
    resume: bool = typer.Option(False), force: bool = typer.Option(False, hidden=True), model: str | None = typer.Option(None, hidden=True),
    case_id: str | None = typer.Option(None, hidden=True), conversation_id: str | None = typer.Option(None, hidden=True),
    domain: str | None = typer.Option(None, hidden=True), attack_vector: str | None = typer.Option(None, hidden=True), limit: int | None = typer.Option(None, min=1, hidden=True),
    skip_judge: bool = typer.Option(False, hidden=True), inference_only: bool = typer.Option(False, hidden=True),
    evaluation_only: bool = typer.Option(False, hidden=True), report_only: bool = typer.Option(False, hidden=True), dry_run: bool = typer.Option(False, hidden=True),
    mock: bool = typer.Option(False, help="Use two offline mock models, a mock judge, and mock embeddings."),
    quick: bool = typer.Option(False, help="Run only five rows as a quick smoke test."),
):
    """Run models sequentially through retrieval, inference, evaluation, and reports."""
    if sum((inference_only, evaluation_only, report_only)) > 1:
        raise typer.BadParameter("inference-only, evaluation-only, and report-only are mutually exclusive")
    if evaluation_only or report_only:
        cfg = _config(config); experiment = cfg.project.output_dir / str(cfg.project.experiment_id)
        if not experiment.exists():
            raise typer.BadParameter("the configured experiment output does not exist")
        if evaluation_only:
            asyncio.run(reevaluate_outputs(cfg, _root(), model, skip_judge))
            typer.echo(f"Re-evaluated existing responses in {experiment}")
        else:
            report(config=config, experiment_id=cfg.project.experiment_id, model=model)
        return
    cfg = _config(config)
    if mock:
        cfg = apply_mock_mode(cfg, _root())
    if quick and limit is None:
        limit = 5
    output = asyncio.run(run_experiment(cfg, _root(), resume=resume, force=force, model_id=model, case_id=case_id, conversation_id=conversation_id, domain=domain, attack_vector=attack_vector, limit=limit, skip_judge=skip_judge, inference_only=inference_only, dry_run=dry_run))
    typer.echo(f"Experiment output: {output}")


