def _root() -> Path:
    return Path.cwd().resolve()


def _config(path: Path):
    return load_config(path, _root())


def _save_setup_configuration(destination: Path, configuration: dict, credentials: dict[str, str] | None = None) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_suffix(".yaml.tmp")
    temporary.write_text("# Generated by ragnarok setup. Secrets are stored in the OS credential store; environment variables may override them.\n" + yaml.safe_dump(configuration, sort_keys=False), encoding="utf-8")
    previous: dict[str, str | None] = {}
    try:
        for credential_id, secret in (credentials or {}).items():
            previous[credential_id] = get_stored_credential(credential_id)
            store_credential(credential_id, secret)
        temporary.replace(destination)
    except Exception:
        for credential_id, old_secret in previous.items():
            if old_secret is None:
                delete_credential(credential_id)
            else:
                store_credential(credential_id, old_secret)
        raise
    finally:
        temporary.unlink(missing_ok=True)


@app.command()
def setup(
    mode: str | None = typer.Option(None, hidden=True),
    provider: str | None = typer.Option(None, hidden=True),
    model: str | None = typer.Option(None, hidden=True),
    base_url: str | None = typer.Option(None, hidden=True),
    endpoint: str | None = typer.Option(None, hidden=True),
    api_key_env: str | None = typer.Option(None, hidden=True),
    judge_mode: str | None = typer.Option(None, hidden=True),
    judge_provider: str | None = typer.Option(None, hidden=True),
    judge_model: str | None = typer.Option(None, hidden=True),
    judge_base_url: str | None = typer.Option(None, hidden=True),
    judge_endpoint: str | None = typer.Option(None, hidden=True),
    judge_api_key_env: str | None = typer.Option(None, hidden=True),
):
    """Interactively create a runnable model and judge configuration."""
    root = _root(); destination = root / "configs" / "evaluation.yaml"
    interactive = all(value is None for value in (
        mode, provider, model, base_url, endpoint, api_key_env,
        judge_mode, judge_provider, judge_model, judge_base_url, judge_endpoint, judge_api_key_env,
    ))
    if interactive:
        from .wizard import SetupCancelled, run_setup_wizard
        try:
            configuration, labels, required_env, credentials = run_setup_wizard(root)
        except SetupCancelled:
            typer.echo("Setup cancelled. No configuration was changed.")
            raise typer.Exit(1)
        _save_setup_configuration(destination, configuration, credentials)
        (root / "outputs").mkdir(exist_ok=True); (root / ".ragnarok" / "cache").mkdir(parents=True, exist_ok=True)
        typer.echo(f"\nConfiguration written to {destination}")
        typer.echo(f"Inference: {labels[0]}")
        typer.echo(f"Judge: {labels[1]}")
        if credentials:
            typer.echo("Credentials saved securely in the operating-system credential store.")
        if required_env:
            typer.echo("Required credential environment variables: " + ", ".join(required_env))
            typer.echo("Set them in your shell before validation; secret values are never stored in YAML.")
        typer.echo("Setup complete. Run 'ragnarok validate --online', then 'ragnarok run'.")
        return

    allowed = {"mock", "ollama", "openai_compatible", "custom_http"}
    if provider is None:
        mode = mode or typer.prompt("Where does the inference model run? [local/remote/mock]", default="local")
        if mode == "mock":
            provider = "mock"
        elif mode == "local":
            provider = typer.prompt("Local inference provider [ollama/openai_compatible/custom_http]", default="ollama")
        elif mode == "remote":
            provider = typer.prompt("Remote inference provider [openai_compatible/custom_http]", default="openai_compatible")
        else:
            raise typer.BadParameter(f"unsupported inference location: {mode}")
    mode = mode or ("mock" if provider == "mock" else "local" if provider == "ollama" else "remote")
    if provider not in allowed:
        raise typer.BadParameter(f"unsupported inference provider: {provider}")
    if mode == "remote" and provider == "ollama":
        raise typer.BadParameter("remote mode supports openai_compatible or custom_http; use local mode for Ollama")
    defaults = {"mock": "safe-mock", "ollama": "llama3.1:8b", "openai_compatible": "model-name", "custom_http": "private-model"}
    model = model or typer.prompt("Inference model", default=defaults[provider])

    inference: dict = {"id": "inference_model", "adapter": provider, "model": model, "temperature": 0}
    if provider == "ollama":
        inference["base_url"] = base_url or typer.prompt("Ollama base URL", default="http://localhost:11434")
    elif provider == "openai_compatible":
        inference["base_url"] = base_url or typer.prompt("OpenAI-compatible base URL")
        inference["api_key_env"] = api_key_env or typer.prompt("Credential environment-variable name")
    elif provider == "custom_http":
        inference["endpoint"] = endpoint or typer.prompt("Custom HTTP endpoint")
        credential = api_key_env or typer.prompt("Credential environment-variable name (leave empty for none)", default="")
        if credential:
            inference["authentication"] = {"type": "bearer", "token_env": credential}

    if judge_provider is None:
        judge_mode = judge_mode or typer.prompt("Where does the judge run? [disabled/same/local/remote/mock]", default="disabled")
        if judge_mode == "disabled":
            judge_provider = "none"
        elif judge_mode == "same":
            judge_provider = provider
        elif judge_mode == "mock":
            judge_provider = "mock"
        elif judge_mode == "local":
            judge_provider = typer.prompt("Local judge provider [ollama/openai_compatible/custom_http]", default="ollama")
        elif judge_mode == "remote":
            judge_provider = typer.prompt("Remote judge provider [openai_compatible/custom_http]", default="openai_compatible")
        else:
            raise typer.BadParameter(f"unsupported judge location: {judge_mode}")
    judge_mode = judge_mode or ("disabled" if judge_provider == "none" else "mock" if judge_provider == "mock" else "same" if judge_provider == provider else "local" if judge_provider == "ollama" else "remote")
    if judge_provider != "none" and judge_provider not in allowed:
        raise typer.BadParameter(f"unsupported judge provider: {judge_provider}")
    if judge_mode == "remote" and judge_provider == "ollama":
        raise typer.BadParameter("remote judge mode supports openai_compatible or custom_http")

    judge: dict = {"enabled": False}
    if judge_provider != "none":
        judge_model = judge_model or typer.prompt("Judge model", default=(model if judge_provider == provider else defaults[judge_provider]))
        judge_entry: dict = {"id": "judge_model", "adapter": judge_provider, "model": judge_model, "temperature": 0}
        if judge_provider == "ollama":
            judge_entry["base_url"] = judge_base_url or typer.prompt("Judge Ollama base URL", default=(base_url or "http://localhost:11434"))
        elif judge_provider == "openai_compatible":
            judge_entry["base_url"] = judge_base_url or typer.prompt("Judge OpenAI-compatible base URL", default=(base_url or ""))
            judge_entry["api_key_env"] = judge_api_key_env or typer.prompt("Judge credential environment-variable name", default=(api_key_env or ""))
        elif judge_provider == "custom_http":
            judge_entry["endpoint"] = judge_endpoint or typer.prompt("Judge custom HTTP endpoint")
            credential = judge_api_key_env or typer.prompt("Judge credential environment-variable name (leave empty for none)", default="")
            if credential:
                judge_entry["authentication"] = {"type": "bearer", "token_env": credential}
        judge = {"enabled": True, "confidence_threshold": 0.7, "model": judge_entry}

    configuration: dict = {"models": [inference], "judge": judge}
    if provider == "mock":
        configuration["rag"] = {"embedding_backend": "mock", "embedding_model": "mock-hash-v1", "cache_dir": ".ragnarok/mock-cache"}
    _save_setup_configuration(destination, configuration)
    (root / "outputs").mkdir(exist_ok=True); (root / ".ragnarok" / "cache").mkdir(parents=True, exist_ok=True)
    typer.echo(f"Configuration written to {destination}")
    typer.echo(f"Inference: {mode} / {provider} / {model}")
    typer.echo(f"Judge: {'disabled' if judge_provider == 'none' else f'{judge_mode} / {judge_provider} / {judge_model}'}")
    typer.echo("Setup complete. Run 'ragnarok validate --online', then 'ragnarok run'.")


@app.command()
def validate(
    config: Path = typer.Option(Path("configs/evaluation.yaml"), exists=True),
    mock: bool = typer.Option(False, help="Validate the built-in offline mock profile."),
    online: bool = typer.Option(False, help="Also contact configured model providers."),
):
    """Validate configuration, benchmark, PDFs, providers, and runtime readiness."""
    cfg = _config(config)
    if mock:
        cfg = apply_mock_mode(cfg, _root())
    result = asyncio.run(validate_environment(cfg, _root(), online=online))
    typer.echo(result.render())
    if not result.ok:
        raise typer.Exit(1)


@app.command()
def status(experiment_id: str | None = typer.Option(None)):
    """Show the lifecycle state of an experiment."""
    outputs = _root() / "outputs"
    candidates = [outputs / experiment_id] if experiment_id else sorted((path for path in outputs.glob("*") if path.is_dir()), key=lambda p: p.stat().st_mtime, reverse=True)
    if not candidates:
        typer.echo("No experiments found."); raise typer.Exit(1)
    typer.echo(json.dumps(Lifecycle(candidates[0] / "status.json").get(), indent=2))


